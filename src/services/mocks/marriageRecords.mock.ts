import type {
  MarriageConsentPerson,
  MarriageParty,
  MarriageRecord,
} from "@/features/parish-admin/records/types";

function party(
  id: string,
  role: MarriageParty["role"],
  data: Omit<MarriageParty, "id" | "role" | "consentPersons"> & {
    consentPersons?: Omit<MarriageConsentPerson, "id">[];
  }
): MarriageParty {
  const { consentPersons = [], ...rest } = data;
  return {
    id,
    role,
    ...rest,
    consentPersons: consentPersons.map((c, i) => ({ ...c, id: `${id}-consent-${i + 1}` })),
  };
}

